#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$SCRIPT_DIR"

SERVER_REPO_URL="https://github.com/ZUST-ICT/school-management-backend.git"
CLIENT_REPO_URL="https://github.com/ZUST-ICT/school-management-frontend.git"
SERVER_DIR="server"
CLIENT_DIR="client"

echo "==> Setting up school-management workspace..."
echo "-- Using Node $(node --version 2>/dev/null || echo 'NOT FOUND') (server repo CI pins 24, client repo CI pins 20 — see README prerequisites)"

if ! command -v pnpm >/dev/null 2>&1; then
  echo "!! pnpm is not installed. Install it with:  npm install -g pnpm@10"
  exit 1
fi

echo "==> Installing workspace root dependencies (concurrently)..."
pnpm install

clone_if_needed() {
  local dir="$1"
  local url="$2"
  if [ -d "$dir" ] && git -C "$dir" rev-parse --is-inside-work-tree >/dev/null 2>&1; then
    echo "-- $dir already cloned, skipping clone (run 'git -C $dir pull' to update)"
  else
    echo "==> Cloning $url into $dir..."
    git clone "$url" "$dir"
  fi
}

clone_if_needed "$SERVER_DIR" "$SERVER_REPO_URL"
clone_if_needed "$CLIENT_DIR" "$CLIENT_REPO_URL"

echo "==> Installing server dependencies..."
pnpm --dir "$SERVER_DIR" install

echo "==> Installing client dependencies..."
pnpm --dir "$CLIENT_DIR" install

SERVER_ENV="$SERVER_DIR/.env"
if [ ! -f "$SERVER_ENV" ]; then
  echo "==> Scaffolding placeholder $SERVER_ENV (no .env.example exists in the backend repo yet)..."
  cat > "$SERVER_ENV" <<'EOF'
# Placeholder values generated by setup.sh — REPLACE_ME values must be filled in
# with real secrets before the server will work. See the workspace README's
# "Environment variables" section for what each of these is and where to get real values.
PORT=5000
MONGODB_URI=REPLACE_ME
JWT_ACCESS_SECRET=REPLACE_ME
JWT_REFRESH_SECRET=REPLACE_ME
NODE_ENV=development
EOF
else
  echo "-- $SERVER_ENV already exists, leaving it untouched"
fi

CLIENT_ENV="$CLIENT_DIR/.env"
CLIENT_ENV_EXAMPLE="$CLIENT_DIR/.env.example"
if [ ! -f "$CLIENT_ENV" ] && [ -f "$CLIENT_ENV_EXAMPLE" ]; then
  echo "==> Copying $CLIENT_ENV_EXAMPLE to $CLIENT_ENV..."
  cp "$CLIENT_ENV_EXAMPLE" "$CLIENT_ENV"
else
  echo "-- $CLIENT_ENV already exists or no .env.example found, leaving as-is"
fi

echo ""
echo "==> Setup complete."
echo "-- server/ -> $SERVER_REPO_URL"
echo "-- client/ -> $CLIENT_REPO_URL"
echo ""
echo "!! ACTION NEEDED: edit $SERVER_ENV and replace the REPLACE_ME values with real"
echo "!! secrets before 'pnpm dev' will fully work (server will otherwise start but"
echo "!! fail to connect to MongoDB)."
echo ""
echo "Next: pnpm dev   (server on :5000, client on :5173)"
